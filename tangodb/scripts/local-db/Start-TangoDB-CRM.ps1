# Launch local TangoDB CRM (Postgres on D: + PostgREST + local auth + Vite).
$ErrorActionPreference = "Stop"
try { $Host.UI.RawUI.WindowTitle = "TangoDB CRM (local)" } catch { }

. "$PSScriptRoot\paths.ps1"

$env:Path = "C:\Program Files\nodejs;C:\pgsql\bin;" + $env:Path

$tangodbRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$envFile = Join-Path $tangodbRoot ".env.local"
$hostedBackup = Join-Path $tangodbRoot ".env.local.hosted"
$postgrestProc = $null
$apiProc = $null

function Wait-OnError {
  param([string]$Message)
  Write-Host ""
  Write-Host $Message -ForegroundColor Red
  Write-Host ""
  Read-Host "Press Enter to close this window"
}

function Get-LanIPv4 {
  $ip = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
    Where-Object {
      $_.IPAddress -notlike "127.*" -and
      $_.IPAddress -notlike "169.254.*" -and
      $_.PrefixOrigin -ne "WellKnown"
    } |
    Sort-Object InterfaceMetric |
    Select-Object -First 1 -ExpandProperty IPAddress
  if ($ip) { return $ip }
  return "127.0.0.1"
}

function Test-ListenPort([int]$Port) {
  return [bool](Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue)
}

function Stop-ListenPort([int]$Port) {
  Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue |
    Select-Object -ExpandProperty OwningProcess -Unique |
    ForEach-Object {
      if ($_ -gt 0) { Stop-Process -Id $_ -Force -ErrorAction SilentlyContinue }
    }
}

try {
  New-Item -ItemType Directory -Force -Path $LocalDbLogs | Out-Null

  if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
    throw "Node.js not found. Install Node.js, then try again."
  }
  if (-not (Get-Command npm -ErrorAction SilentlyContinue)) {
    throw "npm not found. Install Node.js, then try again."
  }
  if (-not (Test-Path (Join-Path $tangodbRoot "node_modules"))) {
    throw "Dependencies missing. In $tangodbRoot run: npm install"
  }

  Write-Host "Starting local TangoDB CRM..."
  & "$PSScriptRoot\ensure-tools.ps1"
  & "$PSScriptRoot\start-postgres.ps1"

  $env:PGPASSWORD = "postgres"
  $env:PGSSLMODE = "disable"
  & (Join-Path $PgsqlBin "psql.exe") -h 127.0.0.1 -p $LocalDbPort -U postgres -d postgres -v ON_ERROR_STOP=1 -f "$PSScriptRoot\grants-postgrest.sql" | Out-Null
  Remove-Item Env:PGPASSWORD, Env:PGSSLMODE -ErrorAction SilentlyContinue

  $lanIp = Get-LanIPv4
  $apiUrl = "http://${lanIp}:54321"
  $appUrl = "http://${lanIp}:3000"

  if ((Test-Path $envFile) -and -not (Test-Path $hostedBackup)) {
    Copy-Item $envFile $hostedBackup -Force
    Write-Host "Backed up cloud .env.local -> .env.local.hosted"
  }

  $anonKey = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0"
  $envBody = @"
# Generated by Start-TangoDB-CRM.ps1 - local laptop stack (not production).
VITE_SUPABASE_URL=$apiUrl
VITE_SUPABASE_ANON_KEY=$anonKey
VITE_SITE_URL=$appUrl
DATABASE_URL=$LocalDbUrl
"@
  $utf8NoBom = New-Object System.Text.UTF8Encoding $false
  [System.IO.File]::WriteAllText($envFile, $envBody, $utf8NoBom)

  $postgrestConf = Join-Path $PSScriptRoot "config\postgrest.conf"
  $postgrestExe = Join-Path $LocalDbBin "postgrest.exe"
  $postgrestOut = Join-Path $LocalDbLogs "postgrest.out.log"
  $postgrestErr = Join-Path $LocalDbLogs "postgrest.err.log"
  $apiOut = Join-Path $LocalDbLogs "local-api.out.log"
  $apiErr = Join-Path $LocalDbLogs "local-api.err.log"

  Stop-ListenPort 54341
  Stop-ListenPort 54321
  Start-Sleep -Seconds 1

  $postgrestProc = Start-Process -FilePath $postgrestExe -ArgumentList $postgrestConf -WorkingDirectory $LocalDbBin -WindowStyle Hidden -RedirectStandardOutput $postgrestOut -RedirectStandardError $postgrestErr -PassThru
  Start-Sleep -Seconds 1
  if (-not (Test-ListenPort 54341)) {
    $hint = if (Test-Path $postgrestErr) { Get-Content $postgrestErr -Raw } else { "" }
    throw "PostgREST did not start on port 54341. $hint"
  }

  $apiProc = Start-Process -FilePath "node" -ArgumentList @("$PSScriptRoot\local-api-server.mjs") -WorkingDirectory $tangodbRoot -WindowStyle Hidden -RedirectStandardOutput $apiOut -RedirectStandardError $apiErr -PassThru
  Start-Sleep -Seconds 1
  if (-not (Test-ListenPort 54321)) {
    $hint = if (Test-Path $apiErr) { Get-Content $apiErr -Raw } else { "" }
    throw "Local API did not start on port 54321. $hint"
  }

  Write-Host ""
  Write-Host "Local API:  $apiUrl"
  Write-Host "CRM UI:     $appUrl"
  Write-Host "Phone:      same URLs on Wi-Fi ($lanIp)"
  Write-Host "Logs:       $LocalDbLogs"
  Write-Host "Keep this window open while you use CRM. Close it to stop."
  Write-Host ""

  Start-Process $appUrl
  Set-Location $tangodbRoot
  npm run dev
  if ($LASTEXITCODE -and $LASTEXITCODE -ne 0) {
    throw "npm run dev exited with code $LASTEXITCODE"
  }
} catch {
  Wait-OnError ("CRM failed to start: " + $_.Exception.Message)
  exit 1
} finally {
  if ($apiProc -and -not $apiProc.HasExited) { Stop-Process -Id $apiProc.Id -Force -ErrorAction SilentlyContinue }
  if ($postgrestProc -and -not $postgrestProc.HasExited) { Stop-Process -Id $postgrestProc.Id -Force -ErrorAction SilentlyContinue }
}
