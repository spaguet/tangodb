export type MessageKey = keyof typeof messages.ru;

/** bootstrap.locale: ru | en | vi (vi → ru fallback per §6.65). */
export function resolveLocale(hint?: string | null): Locale {
  if (hint === "en") return "en";
  return "ru";
}

export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages.ru[key];
}

export function tFill(
  locale: Locale,
  key: MessageKey,
  vars: Record<string, string | number>
): string {
  return Object.entries(vars).reduce(
    (s, [name, value]) => s.replaceAll(`{${name}}`, String(value)),
    t(locale, key)
  );
}

